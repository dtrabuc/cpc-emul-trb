// Mapping complet des touches AZERTY → scancodes CPC
// Basé sur la matrice du clavier Amstrad CPC 464
export const AZERTY_TO_SCANCODE = {
  // Ligne 1 (chiffres)
  '²': 0x00, '&': 0x01, 'é': 0x02, '"': 0x03, "'": 0x04,
  '(': 0x05, '-': 0x06, 'è': 0x07, '_': 0x08, 'ç': 0x09,
  'à': 0x0A, ')': 0x0B, '=': 0x0C,
  '1': 0x0D, '2': 0x0E, '3': 0x0F, '4': 0x10, '5': 0x11,
  '6': 0x12, '7': 0x13, '8': 0x14, '9': 0x15, '0': 0x16,

  // Ligne 2 (AZERTY)
  'a': 0x20, 'z': 0x21, 'e': 0x22, 'r': 0x23, 't': 0x24,
  'y': 0x25, 'u': 0x26, 'i': 0x27, 'o': 0x28, 'p': 0x29,
  '^': 0x2A, '$': 0x2B,

  // Ligne 3 (QSDFGHJKLM)
  'q': 0x30, 's': 0x31, 'd': 0x32, 'f': 0x33, 'g': 0x34,
  'h': 0x35, 'j': 0x36, 'k': 0x37, 'l': 0x38, 'm': 0x39,
  'ù': 0x3A, '*': 0x3B,

  // Ligne 4 (WXCVBN)
  'w': 0x40, 'x': 0x41, 'c': 0x42, 'v': 0x43, 'b': 0x44,
  'n': 0x45, ',': 0x46, ';': 0x47, ':': 0x48, '!': 0x49,

  // Touches spéciales
  'Esc': 0x60,
  'TAB': 0x61,
  'CAPS LOCK': 0x62,
  'SHIFT': 0x63,
  'CTRL': 0x64,
  'SPACE': 0x65,
  'ENTER': 0x66,
  'DEL': 0x67,
  'CLR': 0x68,
  'RETURN': 0x66, // Alias

  // Flèches
  'ArrowUp': 0x70,
  'ArrowDown': 0x71,
  'ArrowLeft': 0x72,
  'ArrowRight': 0x73,

  // Pavé numérique
  '7': 0x74, '8': 0x75, '9': 0x76,
  '4': 0x77, '5': 0x78, '6': 0x79,
  '1': 0x7A, '2': 0x7B, '3': 0x7C,
  '0': 0x7D, '.': 0x7E,
};

export const getScancode = (key) => {
  // Gestion des majuscules
  const lowerKey = key.toLowerCase();
  if (lowerKey in AZERTY_TO_SCANCODE) {
    return AZERTY_TO_SCANCODE[lowerKey];
  }
  return AZERTY_TO_SCANCODE[key] || 0x00;
};